// code_flow.ts
// 1) For loop
for (var i = 0; i < 5; i++) {
    console.log("For Loop iteration: ".concat(i));
}
console.log();
// 2) While loop
var while_loop_counter = 0;
while (while_loop_counter < 3) {
    console.log("While Loop iteration: ".concat(while_loop_counter));
    while_loop_counter++;
}
